/**
 * Self-updating platform facts (WIP 60).
 *
 * Every few minutes Nexi asks the real backend for the rules the code enforces
 * (GET /api/assistant/facts: Seller Pass price, trial length, cancel rule, order
 * statuses...) and writes them to src/knowledge/90-project-facts.generated.md.
 * The keyword index notices the new file within a second and rebuilds in memory.
 *
 * Safety rules:
 *  - A failed fetch, a bad status code or a payload that does not look right NEVER
 *    touches the file. The last good snapshot keeps answering.
 *  - The file is written to a temporary name and renamed, so a half-written file is
 *    never visible to search. It is only rewritten when the text actually changed.
 *  - The endpoint returns platform rules only. No user, order or payment data is
 *    requested or stored here.
 */
const fs = require('fs');
const path = require('path');
const config = require('../config');

const HEADER = [
    '# Platform facts (generated)',
    '',
    '> Written automatically from NextaStore\'s own code by `src/sync/factsSync.js`. Do not edit this file: changes are overwritten at the next sync.',
    '> These values are the authority for prices, limits and status names. Other knowledge files must not repeat them.',
    ''
].join('\n');

// ---- Validation ------------------------------------------------------------
function isNum(v) { return typeof v === 'number' && Number.isFinite(v) && v >= 0; }
function isStrArr(v) { return Array.isArray(v) && v.length > 0 && v.every((x) => typeof x === 'string' && x.trim()); }

/** @returns {string|null} a problem description, or null when the payload is usable. */
function validateFacts(f) {
    if (!f || typeof f !== 'object') return 'payload is not an object';
    const s = f.subscription;
    if (!s || !isNum(s.pricePerMonth) || !isNum(s.trialDays) || typeof s.currency !== 'string') return 'subscription block is missing or malformed';
    if (!Array.isArray(s.periodOptionsMonths) || !s.periodOptionsMonths.every(isNum)) return 'subscription.periodOptionsMonths is malformed';
    if (!Array.isArray(f.badgeTiers) || !f.badgeTiers.length || !f.badgeTiers.every((t) => t && typeof t.label === 'string' && isNum(t.minMonths) && Array.isArray(t.perks))) return 'badgeTiers is missing or malformed';
    const o = f.orders;
    if (!o || !isStrArr(o.statuses) || !o.statusLabels || !o.sellerTransitions || !o.buyerCancel) return 'orders block is missing or malformed';
    const c = o.buyerCancel;
    if (!isNum(c.windowMinutes) || !isNum(c.limit) || !isNum(c.limitWindowDays) || !isStrArr(c.allowedStatuses)) return 'orders.buyerCancel is malformed';
    if (!isStrArr(o.fulfillmentMethods) || !isStrArr(f.listingTypes) || !isStrArr(f.onboardingSteps)) return 'fulfilment, listing types or onboarding steps are malformed';
    // New blocks are optional for compatibility with older backend versions.
    // Malformed optional blocks are ignored by rendering rather than rejecting the payload.
    return null;
}

// ---- Rendering -------------------------------------------------------------
function ugx(n, currency) { return `${currency} ${Number(n).toLocaleString('en-US')}`; }
function list(arr) {
    if (arr.length <= 1) return arr.join('');
    return `${arr.slice(0, -1).join(', ')} and ${arr[arr.length - 1]}`;
}
function orList(arr) {
    if (arr.length <= 1) return arr.join('');
    return `${arr.slice(0, -1).join(', ')} or ${arr[arr.length - 1]}`;
}
