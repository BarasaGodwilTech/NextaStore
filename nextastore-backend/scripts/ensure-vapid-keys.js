#!/usr/bin/env node
'use strict';
/*
 * Local-development helper, called by start-local.bat before the API starts.
 *
 * Push notifications stay switched off ("Push notifications aren't set up on
 * this server yet") unless VAPID_PUBLIC_KEY and VAPID_PRIVATE_KEY are both set.
 * start-local.bat creates .env from .env.example on a fresh checkout, and the
 * example has those two lines empty -- so a new machine would silently have
 * push disabled. This fills them in with a fresh keypair.
 *
 * Deliberately conservative:
 *   - Both keys already set            -> does nothing.
 *   - Only ONE of the two is set       -> does nothing but warn; a half-filled
 *                                          pair is a person's work in progress
 *                                          and overwriting it would invalidate
 *                                          every existing subscription.
 *   - NODE_ENV=production              -> does nothing. Production keys are
 *                                          generated on purpose with
 *                                          `npm run generate:vapid-keys`.
 *   - Any problem at all               -> prints a warning and exits 0, so it
 *                                          can never stop the launcher.
 *
 * Never prints the private key. Keeps the file's own line endings.
 */
const fs = require('fs');
const path = require('path');

const ENV_PATH = path.resolve(__dirname, '..', '.env');

function warn(msg) { console.log('  [push] ' + msg); }

function main() {
  if (process.env.NODE_ENV === 'production') return;
  if (!fs.existsSync(ENV_PATH)) { warn('No .env yet; skipping VAPID key check.'); return; }

  const raw = fs.readFileSync(ENV_PATH, 'utf8');
  const eol = raw.includes('\r\n') ? '\r\n' : '\n';
  const lines = raw.split(/\r?\n/);

  const valueOf = (name) => {
    const line = lines.find((l) => new RegExp('^\\s*' + name + '\\s*=').test(l));
    if (!line) return '';
    return line.slice(line.indexOf('=') + 1).trim().replace(/^["']|["']$/g, '');
  };

  const hasPublic = !!valueOf('VAPID_PUBLIC_KEY');
  const hasPrivate = !!valueOf('VAPID_PRIVATE_KEY');

  if (hasPublic && hasPrivate) { warn('VAPID keys found; device push is available.'); return; }
  if (hasPublic !== hasPrivate) {
    warn('Only one of VAPID_PUBLIC_KEY / VAPID_PRIVATE_KEY is set in .env; leaving both alone.');
    warn('Set both, or delete both and restart, to have a new pair generated.');
    return;
  }

  const webpush = require('web-push');
  const { publicKey, privateKey } = webpush.generateVAPIDKeys();

  const setLine = (name, value) => {
    const i = lines.findIndex((l) => new RegExp('^\\s*' + name + '\\s*=').test(l));
    if (i >= 0) lines[i] = `${name}=${value}`;
    else lines.push(`${name}=${value}`);
  };

  // Drop trailing blank lines so appended keys sit tidily at the end.
  while (lines.length && lines[lines.length - 1] === '') lines.pop();
  if (!lines.some((l) => /^\s*VAPID_/.test(l))) {
    lines.push('', '# Web Push (VAPID) -- generated by scripts/ensure-vapid-keys.js for local development');
  }
  setLine('VAPID_PUBLIC_KEY', publicKey);
  setLine('VAPID_PRIVATE_KEY', privateKey);
  if (!valueOf('VAPID_SUBJECT')) setLine('VAPID_SUBJECT', 'mailto:support@nextastore.app');

  fs.writeFileSync(ENV_PATH, lines.join(eol) + eol);
  warn('Generated a local VAPID keypair and saved it to .env. Device push is now available.');
  warn('Set VAPID_SUBJECT in .env to a real mailto: address before testing on an iPhone.');
}

try { main(); } catch (err) { warn('Skipped VAPID key check: ' + err.message); }
process.exit(0);
