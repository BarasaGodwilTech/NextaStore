#!/usr/bin/env node
'use strict';
/*
 * WIP 96: keeps service-worker.js CACHE_VERSION honest.
 *
 * The worker caches every same-origin .js/.css file stale-while-revalidate, and only drops old caches when CACHE_VERSION
 * changes. Change a script or stylesheet without bumping it and returning visitors keep running the old file next to new
 * ones. `sw-assets.hash` (project root, committed) records a content hash of every js/**\/*.js and css/**\/*.css file
 * together with the CACHE_VERSION that shipped with that content. qa-static fails when the files and the record disagree.
 *
 *   node scripts/sw-assets-hash.js            show status (exit 1 if out of date)
 *   node scripts/sw-assets-hash.js --check    same, quiet on success
 *   node scripts/sw-assets-hash.js --write    regenerate sw-assets.hash. Refuses if the assets changed but CACHE_VERSION
 *                                             was not bumped first.     (npm run sw-assets-hash)
 *
 * Line endings are normalised (CRLF -> LF) before hashing so a Windows checkout hashes the same as Linux.
 */
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT_DEFAULT = path.resolve(__dirname, '..', '..');
const HASH_FILE = 'sw-assets.hash';
const DIRS = [['js', /\.js$/i], ['css', /\.css$/i]];
const sha = (buf) => crypto.createHash('sha256').update(buf).digest('hex');
const normalise = (buf) => Buffer.from(buf.toString('latin1').replace(/\r\n/g, '\n'), 'latin1');

function walk(dir, rx, rel, out) {
  if (!fs.existsSync(dir)) return;
  for (const name of fs.readdirSync(dir).sort()) {
    const full = path.join(dir, name); const r = rel + '/' + name; const st = fs.statSync(full);
    if (st.isDirectory()) walk(full, rx, r, out);
    else if (rx.test(name)) out[r] = sha(normalise(fs.readFileSync(full)));
  }
}
/** { 'css/main.css': '<sha256>', ... } for every precacheable JS/CSS file under root */
function collect(root) {
  const out = {};
  for (const [d, rx] of DIRS) walk(path.join(root || ROOT_DEFAULT, d), rx, d, out);
  return out;
}
const sortedKeys = (files) => Object.keys(files).sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
const combinedOf = (files) => sha(Buffer.from(sortedKeys(files).map((k) => files[k] + '  ' + k + '\n').join(''), 'utf8'));
const versionOf = (swSource) => { const m = /CACHE_VERSION = '(v\d+)'/.exec(swSource || ''); return m ? m[1] : null; };

function render(files, version) {
  return [
    '# sw-assets.hash: generated by nextastore-backend/scripts/sw-assets-hash.js (npm run sw-assets-hash). Do not edit by hand.',
    '# Content hash of every js/**/*.js and css/**/*.css file (the service worker caches all of them) and the CACHE_VERSION',
    '# in service-worker.js that shipped with that content. qa-static fails if the files change without both being updated.',
    'cache-version: ' + version,
    'combined: ' + combinedOf(files),
    ...sortedKeys(files).map((k) => files[k] + '  ' + k),
    ''
  ].join('\n');
}
function parse(text) {
  if (typeof text !== 'string') return null;
  const rec = { version: null, combined: null, files: {} };
  for (const line of text.split(/\r?\n/)) {
    let m;
    if ((m = /^cache-version:\s*(v\d+)\s*$/.exec(line))) rec.version = m[1];
    else if ((m = /^combined:\s*([0-9a-f]{64})\s*$/.exec(line))) rec.combined = m[1];
    else if ((m = /^([0-9a-f]{64})\s{2}(\S+)\s*$/.exec(line))) rec.files[m[2]] = m[1];
  }
  return rec.version && rec.combined ? rec : null;
}
function diff(recordedFiles, files) {
  const changed = [];
  for (const k of sortedKeys(files)) { if (!(k in recordedFiles)) changed.push('added ' + k); else if (recordedFiles[k] !== files[k]) changed.push('changed ' + k); }
  for (const k of sortedKeys(recordedFiles)) if (!(k in files)) changed.push('removed ' + k);
  return changed;
}
/**
 * Is the record consistent with the files and the worker? -> { ok, problems[] }
 *  - the JS/CSS content must match what was recorded (otherwise: assets changed, record not regenerated)
 *  - the record must name the CACHE_VERSION the worker has (otherwise: version and record out of step)
 *  - the record must not have been edited by hand (its combined hash must match its own file list)
 */
function evaluate({ recorded, files, version }) {
  const problems = [];
  if (!recorded) return { ok: false, problems: [HASH_FILE + ' is missing or unreadable: run `npm run sw-assets-hash` in nextastore-backend'] };
  if (!version) problems.push('service-worker.js has no CACHE_VERSION = \'vNN\'');
  const changed = diff(recorded.files, files);
  if (changed.length) problems.push('JS/CSS changed since ' + HASH_FILE + ' was recorded (' + changed.slice(0, 6).join(', ') + (changed.length > 6 ? ', +' + (changed.length - 6) + ' more' : '') + '): bump CACHE_VERSION in service-worker.js, then run `npm run sw-assets-hash`');
  if (version && recorded.version !== version) problems.push(HASH_FILE + ' records cache-version ' + recorded.version + ' but service-worker.js has ' + version + ': run `npm run sw-assets-hash`');
  if (combinedOf(recorded.files) !== recorded.combined) problems.push(HASH_FILE + ' was edited by hand (its combined hash does not match its own file list): regenerate it');
  return { ok: problems.length === 0, problems };
}
/** May --write regenerate? Not when assets changed but CACHE_VERSION is still the recorded one. */
function canWrite({ recorded, files, version }) {
  if (!version) return { ok: false, reason: 'service-worker.js has no CACHE_VERSION' };
  if (recorded && diff(recorded.files, files).length && recorded.version === version) return { ok: false, reason: 'JS/CSS changed but CACHE_VERSION is still ' + version + ': bump it in service-worker.js first, then re-run' };
  return { ok: true };
}

function load(root) {
  const hashPath = path.join(root, HASH_FILE);
  return { hashPath, recorded: fs.existsSync(hashPath) ? parse(fs.readFileSync(hashPath, 'utf8')) : null, files: collect(root), version: versionOf(fs.readFileSync(path.join(root, 'service-worker.js'), 'utf8')) };
}

module.exports = { HASH_FILE, collect, combinedOf, versionOf, render, parse, diff, evaluate, canWrite, load };

if (require.main === module) {
  const args = process.argv.slice(2); const ri = args.indexOf('--root');
  const root = path.resolve(ri >= 0 ? args[ri + 1] : ROOT_DEFAULT);
  const state = load(root);
  if (args.includes('--write')) {
    const w = canWrite(state);
    if (!w.ok) { console.error('sw-assets-hash: refusing to write. ' + w.reason); process.exit(1); }
    fs.writeFileSync(state.hashPath, render(state.files, state.version));
    console.log('sw-assets-hash: wrote ' + HASH_FILE + ' (' + Object.keys(state.files).length + ' files, cache-version ' + state.version + ', combined ' + combinedOf(state.files).slice(0, 12) + ')');
  } else {
    const r = evaluate(state);
    if (!r.ok) { r.problems.forEach((p) => console.error('sw-assets-hash: ' + p)); process.exit(1); }
    if (!args.includes('--check')) console.log('sw-assets-hash: OK (' + Object.keys(state.files).length + ' files, cache-version ' + state.version + ')');
  }
}
